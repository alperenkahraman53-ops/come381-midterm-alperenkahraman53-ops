-- Odev 1: Once temiz bir veritabaninda calistirin.
CREATE TABLE customer (
 customer_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 full_name varchar(120), email varchar(180), city varchar(80)
);
CREATE TABLE product (
 product_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 product_name varchar(120), sku varchar(30), category varchar(50),
 list_price numeric(10,2), discount_price numeric(10,2), stock_quantity integer
);
CREATE TABLE customer_order (
 order_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 customer_id integer, order_date date, status varchar(20),
 CONSTRAINT fk_order_customer FOREIGN KEY (customer_id) REFERENCES customer(customer_id) ON DELETE RESTRICT
);
CREATE TABLE order_item (
 order_item_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 order_id integer, product_id integer, quantity integer, unit_price numeric(10,2),
 CONSTRAINT fk_item_order FOREIGN KEY (order_id) REFERENCES customer_order(order_id) ON DELETE CASCADE,
 CONSTRAINT fk_item_product FOREIGN KEY (product_id) REFERENCES product(product_id) ON DELETE RESTRICT
);
